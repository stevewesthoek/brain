const REVIEW_STATES = ['needs_review', 'accepted', 'rejected', 'deferred', 'archived'];

export function projectIngestionReview(report) {
  const items = report.envelopes.map((envelope) => ({
    review_state: 'needs_review',
    decision_options: REVIEW_STATES,
    source_file: envelope.identity.source_reference.ref,
    ingestion_id: envelope.identity.ingestion_id,
    timestamp: envelope.identity.created_at,
    source_hash: envelope.identity.source_revision,
    detected_type: envelope.content.detected_format,
    extracted_metadata: envelope.content.metadata,
    content_summary: envelope.content.summary_reference?.ref ?? 'No semantic summary generated by this adapter.',
    confidence: envelope.content.confidence,
    uncertainty: envelope.content.uncertainty,
    mind_impact: envelope.governance.mind_impact,
    brain_impact: envelope.governance.brain_impact,
    privacy: envelope.governance.privacy_classification,
    freshness: envelope.governance.freshness,
    review_required: envelope.governance.review_required,
    evidence_references: envelope.evidence.source_references,
    promotion_authority: 'human-approved-bounded-transaction',
  }));
  const failures = report.failures.map((failure) => ({
    review_state: 'needs_review',
    decision_options: REVIEW_STATES,
    source_file: `mind/inbox/new/${failure.file}`,
    issue: failure.code,
    details: failure.message ?? failure.errors ?? 'Processing failed.',
    promotion_authority: 'human-approved-bounded-transaction',
  }));
  return {
    projection_version: '1.0.0',
    generated_at: report.generated_at,
    source: report.source,
    writes_to_mind: false,
    automatic_promotion: false,
    items,
    failures,
  };
}

export function renderIngestionReviewMarkdown(projection) {
  const lines = [
    '# Mind Inbox Human Review',
    '',
    `Generated: ${projection.generated_at}`,
    `Source: ${projection.source}`,
    '',
    `Items requiring review: ${projection.items.length + projection.failures.length}`,
    '- Review states are workflow states only; they are not memory promotion.',
    '- Writes to Mind: false',
    '- Automatic promotion: false',
    '',
  ];
  projection.items.forEach((item, index) => {
    lines.push(`## ${index + 1}. ${item.source_file}`);
    lines.push('', `- Review state: **${item.review_state}**`);
    lines.push(`- Decision options: ${item.decision_options.join(', ')}`);
    lines.push(`- Ingestion ID: \`${item.ingestion_id}\``);
    lines.push(`- Timestamp: ${item.timestamp}`);
    lines.push(`- Source hash: \`${item.source_hash}\``);
    lines.push(`- Detected type: ${item.detected_type}`);
    lines.push(`- Content summary: ${item.content_summary}`);
    lines.push(`- Confidence: ${item.confidence}`);
    lines.push(`- Uncertainty: ${item.uncertainty.join('; ') || 'none recorded'}`);
    lines.push(`- Mind impact: ${item.mind_impact}; Brain impact: ${item.brain_impact}`);
    lines.push(`- Privacy: ${item.privacy}; Freshness: ${item.freshness}`);
    lines.push(`- Review required: ${item.review_required}`);
    lines.push(`- Promotion authority: ${item.promotion_authority}`);
    lines.push('');
  });
  projection.failures.forEach((failure, index) => {
    lines.push(`## Failure ${index + 1}. ${failure.source_file}`);
    lines.push('', `- Review state: **${failure.review_state}**`);
    lines.push(`- Decision options: ${failure.decision_options.join(', ')}`);
    lines.push(`- Issue: ${failure.issue}`);
    lines.push(`- Details: ${Array.isArray(failure.details) ? failure.details.join('; ') : failure.details}`);
    lines.push('');
  });
  lines.push('Human review must use the existing Mind/Brain approval and receipt flow. This projection does not apply decisions.');
  return `${lines.join('\n')}\n`;
}
